"""
AgisRecon2 - TXT Output

Handles formatting and saving reconnaissance results in
plain text (.txt) format.

The generated file records the scan output together with
the external tool that produced it, so a saved scan can be
traced back to the exact tool and command used.
"""

import re
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

try:
    from config.tools import TOOLS
except ImportError:
    TOOLS: Dict[str, str] = {}


# ANSI escape sequences emitted by colourful CLI tools.
ANSI_ESCAPE_PATTERN = re.compile(r"\x1b\[[0-9;?]*[ -/]*[@-~]")


class TXTOutput:
    """Handle AgisRecon2 plain text output."""

    def __init__(
        self,
        output_dir: Optional[Union[str, Path]] = None,
    ):
        """
        Initialize the plain text output handler.

        Args:
            output_dir: Directory where plain text results
                        will be stored.
        """

        if output_dir is None:
            output_dir = Path("output") / "txt"

        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(
            parents=True,
            exist_ok=True,
        )

    # ---------------------------------------------------------
    # Tool resolution
    # ---------------------------------------------------------

    @staticmethod
    def resolve_tool(
        module: Optional[str] = None,
        tool: Optional[str] = None,
    ) -> str:
        """
        Resolve the external tool used for a scan.

        An explicitly supplied tool always wins. Otherwise the
        tool registry is consulted using the module name, and
        the module name itself is used as a final fallback.

        Args:
            module: Name of the module that produced the results.
            tool: Explicit tool name or executable path.

        Returns:
            The resolved tool name.
        """

        if tool:
            return str(tool)

        if not module:
            return "Unknown"

        module_name = str(module).strip().lower()

        return TOOLS.get(module_name, module_name)

    # ---------------------------------------------------------
    # Format results
    # ---------------------------------------------------------

    def format_results(
        self,
        results: Any,
        target: Optional[str] = None,
        module: Optional[str] = None,
        tool: Optional[str] = None,
        command: Optional[str] = None,
        title: str = "AgisRecon2 Reconnaissance Report",
    ) -> str:
        """
        Convert reconnaissance results into plain text.

        Args:
            results: Results returned by a reconnaissance module.
            target: Target being scanned.
            module: Name of the module that produced the results.
            tool: External tool used by the scan.
            command: Command executed by the scan.
            title: Report title.

        Returns:
            The formatted plain text report.
        """

        timestamp = datetime.now().strftime(
            "%Y-%m-%d %H:%M:%S"
        )

        resolved_tool = self.resolve_tool(
            module=module,
            tool=tool,
        )

        lines = [
            "=" * 60,
            title,
            "=" * 60,
            "",
            "Scan Information",
            "-" * 60,
            f"Tool      : {resolved_tool}",
            f"Module    : {module or 'N/A'}",
            f"Target    : {target or 'N/A'}",
            f"Command   : {command or 'N/A'}",
            f"Timestamp : {timestamp}",
            f"Results   : {self._count_results(results)}",
            "",
            "=" * 60,
            "Results",
            "=" * 60,
            "",
        ]

        lines.extend(
            self._format_value(results)
        )

        lines.extend(
            [
                "",
                "-" * 60,
                "Generated by AgisRecon2",
                "",
            ]
        )

        return "\n".join(lines)

    # ---------------------------------------------------------
    # Format values
    # ---------------------------------------------------------

    def _format_value(
        self,
        value: Any,
        level: int = 0,
    ) -> List[str]:
        """Format different Python data types as plain text."""

        lines: List[str] = []

        if isinstance(value, dict):
            return self._format_dict(value, level)

        if isinstance(value, (list, tuple, set)):
            return self._format_list(list(value), level)

        if value is None:
            return [f"{self._indent(level + 1)}N/A"]

        text = self._safe_text(value)

        return [
            f"{self._indent(level + 1)}{line}"
            for line in (text.splitlines() or [""])
        ]

    def _format_dict(
        self,
        data: Dict[str, Any],
        level: int = 0,
    ) -> List[str]:
        """Format a dictionary as plain text."""

        lines: List[str] = []
        indent = self._indent(level + 1)

        if not data:
            lines.append(f"{indent}(no data)")
            return lines

        for key, item in data.items():
            label = self._safe_text(key)

            if isinstance(
                item,
                (dict, list, tuple, set),
            ):
                lines.append(f"{indent}{label}:")
                lines.extend(
                    self._format_value(item, level + 1)
                )
            else:
                lines.append(
                    f"{indent}{label} : "
                    f"{self._safe_text(item)}"
                )

        return lines

    def _format_list(
        self,
        items: List[Any],
        level: int = 0,
    ) -> List[str]:
        """Format a list as plain text."""

        lines: List[str] = []
        indent = self._indent(level + 1)

        if not items:
            lines.append(f"{indent}(no results)")
            return lines

        for index, item in enumerate(items, start=1):

            if isinstance(item, dict):
                lines.append(f"{indent}[{index}]")
                lines.extend(
                    self._format_dict(item, level + 1)
                )

            elif isinstance(
                item,
                (list, tuple, set),
            ):
                lines.append(f"{indent}[{index}]")
                lines.extend(
                    self._format_list(
                        list(item),
                        level + 1,
                    )
                )

            else:
                lines.append(
                    f"{indent}- "
                    f"{self._safe_text(item)}"
                )

        return lines

    # ---------------------------------------------------------
    # Save
    # ---------------------------------------------------------

    def save(
        self,
        results: Any,
        filename: Optional[str] = None,
        target: Optional[str] = None,
        module: Optional[str] = None,
        tool: Optional[str] = None,
        command: Optional[str] = None,
        title: str = "AgisRecon2 Reconnaissance Report",
    ) -> Path:
        """
        Save reconnaissance results as a plain text file.

        Returns:
            Path to the generated plain text file.
        """

        content = self.format_results(
            results=results,
            target=target,
            module=module,
            tool=tool,
            command=command,
            title=title,
        )

        if filename is None:
            filename = self._generate_filename(
                target=target,
                module=module,
            )

        if not filename.endswith(".txt"):
            filename += ".txt"

        file_path = self.output_dir / filename

        file_path.write_text(
            content,
            encoding="utf-8",
        )

        return file_path

    # ---------------------------------------------------------
    # Filename generation
    # ---------------------------------------------------------

    @staticmethod
    def _generate_filename(
        target: Optional[str] = None,
        module: Optional[str] = None,
    ) -> str:
        """Generate a timestamp-based plain text filename."""

        timestamp = datetime.now().strftime(
            "%Y%m%d_%H%M%S"
        )

        target_name = (
            str(target)
            .replace("://", "_")
            .replace("/", "_")
            .replace("\\", "_")
            .replace(":", "_")
            if target
            else "target"
        )

        module_name = (
            str(module).replace(" ", "_")
            if module
            else "scan"
        )

        return (
            f"{target_name}_"
            f"{module_name}_"
            f"{timestamp}.txt"
        )

    # ---------------------------------------------------------
    # Utility
    # ---------------------------------------------------------

    @staticmethod
    def _indent(level: int) -> str:
        """Return the indentation string for a nesting level."""

        return "  " * level

    @staticmethod
    def _count_results(results: Any) -> int:
        """Count the number of results held by a result set."""

        if isinstance(results, dict):
            return len(results)

        if isinstance(results, (list, tuple, set)):
            return len(results)

        return 0 if results is None else 1

    @staticmethod
    def _safe_text(value: Any) -> str:
        """Convert a value into readable plain text."""

        text = str(value)

        # Remove terminal colour codes so the file stays clean.
        text = ANSI_ESCAPE_PATTERN.sub("", text)

        return text


# -------------------------------------------------------------
# Default plain text output instance
# -------------------------------------------------------------

txt_output = TXTOutput()


# -------------------------------------------------------------
# Convenience functions
# -------------------------------------------------------------

def save_txt(
    results: Any,
    filename: Optional[str] = None,
    target: Optional[str] = None,
    module: Optional[str] = None,
    tool: Optional[str] = None,
    command: Optional[str] = None,
    title: str = "AgisRecon2 Reconnaissance Report",
) -> Path:
    """Save results as a plain text report."""

    return txt_output.save(
        results=results,
        filename=filename,
        target=target,
        module=module,
        tool=tool,
        command=command,
        title=title,
    )


def format_txt(
    results: Any,
    target: Optional[str] = None,
    module: Optional[str] = None,
    tool: Optional[str] = None,
    command: Optional[str] = None,
    title: str = "AgisRecon2 Reconnaissance Report",
) -> str:
    """Create a plain text report without saving it."""

    return txt_output.format_results(
        results=results,
        target=target,
        module=module,
        tool=tool,
        command=command,
        title=title,
    )
